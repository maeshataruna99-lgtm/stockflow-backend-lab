package dev.stockflow.gateway.config;

import static com.github.tomakehurst.wiremock.client.WireMock.aResponse;
import static com.github.tomakehurst.wiremock.client.WireMock.equalTo;
import static com.github.tomakehurst.wiremock.client.WireMock.get;
import static com.github.tomakehurst.wiremock.client.WireMock.getRequestedFor;
import static com.github.tomakehurst.wiremock.client.WireMock.matching;
import static com.github.tomakehurst.wiremock.client.WireMock.stubFor;
import static com.github.tomakehurst.wiremock.client.WireMock.urlEqualTo;
import static com.github.tomakehurst.wiremock.client.WireMock.verify;
import static org.assertj.core.api.Assertions.assertThat;

import dev.stockflow.gateway.security.JwtService;
import java.util.List;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.autoconfigure.web.reactive.AutoConfigureWebTestClient;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.cloud.contract.wiremock.AutoConfigureWireMock;
import org.springframework.http.HttpHeaders;
import org.springframework.http.HttpStatus;
import org.springframework.test.web.reactive.server.WebTestClient;

@SpringBootTest(webEnvironment = SpringBootTest.WebEnvironment.RANDOM_PORT)
@AutoConfigureWebTestClient
@AutoConfigureWireMock(port = 0)
class RequestIdGatewayTest {

    private static final String UUID_PATTERN = "[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}";

    @Autowired
    private WebTestClient webTestClient;

    @Autowired
    private JwtService jwtService;

    private String bearer() {
        return "Bearer " + jwtService.generateToken("user-1", List.of("ROLE_USER"));
    }

    private void stubCategories() {
        stubFor(get(urlEqualTo("/api/v1/categories")).willReturn(aResponse().withStatus(200).withBody("[]")));
    }

    @Test
    @DisplayName("A request without an ID gets a generated one, sent downstream and returned")
    void generatesRequestIdWhenAbsent() {
        stubCategories();

        webTestClient.get().uri("/api/v1/categories")
                .header(HttpHeaders.AUTHORIZATION, bearer())
                .exchange()
                .expectStatus().isOk()
                .expectHeader().value("X-Request-Id", id -> assertThat(id).matches(UUID_PATTERN));

        verify(getRequestedFor(urlEqualTo("/api/v1/categories"))
                .withHeader("X-Request-Id", matching(UUID_PATTERN)));
    }

    @Test
    @DisplayName("A well-formed client ID is kept end to end")
    void keepsValidClientRequestId() {
        stubCategories();

        webTestClient.get().uri("/api/v1/categories")
                .header(HttpHeaders.AUTHORIZATION, bearer())
                .header("X-Request-Id", "client-trace-42")
                .exchange()
                .expectStatus().isOk()
                .expectHeader().valueEquals("X-Request-Id", "client-trace-42");

        verify(getRequestedFor(urlEqualTo("/api/v1/categories")).withHeader("X-Request-Id", equalTo("client-trace-42")));
    }

    @Test
    @DisplayName("A malformed client ID is never echoed: it is replaced by a generated one")
    void replacesMalformedClientRequestId() {
        stubCategories();

        webTestClient.get().uri("/api/v1/categories")
                .header(HttpHeaders.AUTHORIZATION, bearer())
                .header("X-Request-Id", "bad id <script>")
                .exchange()
                .expectStatus().isOk()
                .expectHeader().value("X-Request-Id", id -> assertThat(id).matches(UUID_PATTERN));
    }

    @Test
    @DisplayName("Responses generated by the gateway itself carry the ID too")
    void gatewayErrorResponsesCarryRequestId() {
        webTestClient.get().uri("/api/v1/categories")
                .exchange()
                .expectStatus().isEqualTo(HttpStatus.UNAUTHORIZED)
                .expectHeader().value("X-Request-Id", id -> assertThat(id).matches(UUID_PATTERN));
    }

    @Test
    @DisplayName("The downstream Server header is removed and nosniff is added")
    void responseHeadersAreTransformed() {
        stubFor(get(urlEqualTo("/api/v1/categories")).willReturn(aResponse()
                .withStatus(200).withHeader("Server", "internal-app/9.9").withBody("[]")));

        webTestClient.get().uri("/api/v1/categories")
                .header(HttpHeaders.AUTHORIZATION, bearer())
                .exchange()
                .expectStatus().isOk()
                .expectHeader().doesNotExist("Server")
                .expectHeader().valueEquals("X-Content-Type-Options", "nosniff");
    }
}
